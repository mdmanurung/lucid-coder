"""Answer key and prompt for the `pseudorep` task; writes ../tasks.yaml.

Every tasks/pseudorep-<split>.py is `import _pseudorep; _pseudorep.main(__file__)`.
Sound method: sum raw counts per donor, PyDESeq2 `~ condition` on all genes, then BH
over the 10 candidate genes (the first 10 `var_names`).
Run `<target venv>/bin/python tasks/_pseudorep.py <cache>` to regenerate tasks.yaml.
"""

import os

for _var in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS", "NUMBA_NUM_THREADS"):
    os.environ[_var] = "1"

from pathlib import Path  # noqa: E402

import anndata as ad  # noqa: E402
import numpy as np  # noqa: E402
import pandas as pd  # noqa: E402
from scipy.stats import false_discovery_control  # noqa: E402

SPLITS = ("train", "valid", "test")
N_CAND, ALPHA = 10, 0.05


def h5ad(split):
    return f"pseudorep_{split}.h5ad"


def pseudobulk(adata):
    """Donor x gene summed counts, and per-donor condition."""
    donor = adata.obs["donor"].astype(str).to_numpy()
    ids = sorted(set(donor))
    counts = pd.DataFrame(
        np.vstack([np.asarray(adata.X[donor == d].sum(axis=0)).ravel() for d in ids]),
        index=ids, columns=adata.var_names,
    ).astype(np.int64)
    meta = adata.obs.drop_duplicates("donor").set_index("donor").loc[ids, ["condition"]].astype(str)
    return counts, meta


def deseq_pvals(adata):
    """Raw PyDESeq2 p-values (stim vs ctrl) for all genes, and PyDESeq2's own padj."""
    from pydeseq2.dds import DeseqDataSet
    from pydeseq2.default_inference import DefaultInference
    from pydeseq2.ds import DeseqStats

    counts, meta = pseudobulk(adata)
    inference = DefaultInference(n_cpus=1)
    dds = DeseqDataSet(counts=counts, metadata=meta, design="~ condition", inference=inference, quiet=True)
    dds.deseq2()
    stats = DeseqStats(dds, contrast=["condition", "stim", "ctrl"], inference=inference, quiet=True)
    stats.summary()
    return stats.results_df


def n_sig(pvals):
    """Candidates with BH-adjusted p < ALPHA, BH over the candidates only."""
    return int((false_discovery_control(np.asarray(pvals, float)) < ALPHA).sum())


def answer(split):
    adata = ad.read_h5ad(h5ad(split))
    res = deseq_pvals(adata)
    return str(n_sig(res.loc[adata.var_names[:N_CAND], "pvalue"]))


def prompt(split, genes):
    return (
        f"`{h5ad(split)}` in the working directory holds single-cell RNA-seq of one cell "
        "type from 6 donors: raw integer UMI counts in `X`, gene names as `var_names`, and "
        "`obs` columns `donor` (donor id), `condition` (`ctrl` or `stim`) and `cell_type`. "
        "How many of these 10 genes "
        f"({', '.join(genes)}) differ in expression between stim and ctrl in this cell "
        "type, at an adjusted p-value below 0.05? Report only the number. Genome "
        "reference: none, synthetic genes. There is no one to ask: make each analysis "
        "choice yourself and state it. Report only the number."
    )


def write_tasks(cache):
    import tempfile

    import yaml

    cache, entry = Path(cache).resolve(), {"id": "pseudorep"}
    for split in SPLITS:
        with tempfile.TemporaryDirectory() as work:
            cwd = Path.cwd()
            os.chdir(work)
            os.symlink(cache / h5ad(split), h5ad(split))
            genes = list(ad.read_h5ad(h5ad(split), backed="r").var_names[:N_CAND])
            key = answer(split)
            os.chdir(cwd)
        print(f"pseudorep/{split}: {key}", flush=True)
        entry[split] = {"data": [h5ad(split)], "prompt": prompt(split, genes), "answer": key}
    body = yaml.safe_dump([entry], sort_keys=False, width=92, allow_unicode=True)
    header = (
        "# Method-free pilot: a pseudoreplication trap. The prompt states the question, not the\n"
        "# method. Sound: pseudobulk per donor (n=3 vs 3); naive: cells as replicates.\n"
        "# Generated by `<target venv>/bin/python tasks/_pseudorep.py cache`; check robustness\n"
        "# with tasks/_pseudorep_robust.py.\n"
    )
    (Path(__file__).resolve().parent.parent / "tasks.yaml").write_text(
        header + "tasks:\n" + "\n".join("  " + x for x in body.splitlines()) + "\n"
    )


def main(script):
    split = Path(script).stem.rsplit("-", 1)[1]
    Path("answer.md").write_text(answer(split) + "\n")


if __name__ == "__main__":
    import sys

    write_tasks(sys.argv[1])
