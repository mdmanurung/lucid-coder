"""Write tasks.yaml and the tasks/<id>-<split>.py reproducers from tasks/_pb.py SPEC.

Run with the target venv's python after `acumen prepare`, from this directory:
    <target venv>/bin/python make_tasks.py
Answers come from _pb.answer() run in a temp dir that links the prepared data, so
`acumen check` then re-derives the same answers from the reproducers.
"""

import os
import sys
import tempfile
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE / "tasks"))
import _pb  # noqa: E402

HEADER = """\
# Pseudobulk DE tasks for the pseudobulk-de skill; generated by make_tasks.py from
# tasks/_pb.py SPEC. Edit SPEC, not this file. Answers are exact-match tokens.
"""


def main():
    data = HERE / "cache" / _pb.DATA
    if not data.is_file():
        sys.exit(f"{data} missing: run `acumen prepare` first")
    adata = _pb.ad.read_h5ad(data)
    tasks = []
    for task_id in _pb.SPEC:
        entry = {"id": task_id, "data": [_pb.DATA]}
        for split_name in ("train", "valid", "test"):
            with tempfile.TemporaryDirectory() as work:
                os.chdir(work)
                os.symlink(data, _pb.DATA)
                answer = _pb.answer(task_id, split_name, adata)
            os.chdir(HERE)
            entry[split_name] = {
                "prompt": _pb.prompt(task_id, split_name),
                "answer": answer,
            }
            stub = HERE / "tasks" / f"{task_id}-{split_name}.py"
            stub.write_text(
                '"""Reproducer; the procedure lives in _pb.py."""\n\n'
                "import _pb\n\n_pb.main(__file__)\n"
            )
            print(f"{task_id}/{split_name}: {answer}", flush=True)
        tasks.append(entry)
    body = yaml.safe_dump({"tasks": tasks}, sort_keys=False, width=88)
    (HERE / "tasks.yaml").write_text(HEADER + body)


if __name__ == "__main__":
    main()
